def score(d, pred):
    err = np.asarray(pred) - d.y.to_numpy()
    volume = d.y.sum()
    daily = pd.DataFrame({'date': d.cutoff.to_numpy(), 'y': d.y.to_numpy(), 'abs': abs(err), 'err': err}).groupby('date').sum()
    return dict(WAPE=abs(err).sum()/volume, Bias=err.sum()/volume,
                Score=(abs(err).sum()+abs(err.sum()))/volume,
                Daily=((daily['abs']+daily.err.abs())/daily.y).mean())

def meta(train, query, alpha, cols=methods, weights=False):
    pred = pd.Series(index=query.index, dtype=float)
    rows = []
    for h, q in query.groupby('horizon'):
        t = train[train.horizon.eq(h)]
        x = t[cols].to_numpy(dtype=float)/100000
        y = t.y.to_numpy(dtype=float)/100000
        xm, ym = x.mean(axis=0), y.mean()
        xc = x-xm
        coef = np.linalg.solve(xc.T@xc+alpha*np.eye(len(cols)), xc.T@(y-ym))
        intercept = ym-xm@coef
        pred.loc[q.index] = np.maximum(0, (q[cols].to_numpy()/100000@coef+intercept)*100000)
        rows.append({'h':h, **dict(zip(cols,coef)), 'intercept':intercept*100000})
    return (pred, pd.DataFrame(rows)) if weights else pred

